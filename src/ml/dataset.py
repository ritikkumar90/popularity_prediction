import logging
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch_geometric.data import Dataset, HeteroData
from torch_geometric.loader import DataLoader

from src.config import Config

log = logging.getLogger(__name__)

def to_target(y: float) -> float:
    """Log-transform the ground truth for stable MSLE/MAPE training."""
    return float(np.log1p(y))


class PostGraphDataset(Dataset):
    def __init__(self, cfg: Config, split: str, config_hash: str):
        """
        PyTorch Geometric Dataset reading from sharded caches.
        Args:
            cfg: Project configuration
            split: 'train', 'val', or 'test'
            config_hash: The SHA256 prefix generated by features.py
        """
        super().__init__()
        self.cfg = cfg
        self.base_dir = cfg.run.base_path
        self.dataset_name = cfg.dataset_name
        
        self.splits_dir = self.base_dir / "data" / "splits" / self.dataset_name
        # Match the sample output directory pattern from features.py
        self.ml_dir = self.base_dir / cfg.run.output_dir / self.dataset_name / "samples" / config_hash
        
        if not self.ml_dir.exists():
            raise FileNotFoundError(f"Missing extracted features at {self.ml_dir}. Run features.py first.")
            
        # Filter posts strictly by the requested split
        meta = pd.read_parquet(self.splits_dir / "split_meta.parquet")
        self.split_posts = set(meta[meta["split"] == split]["post_id"])
        
        self.labels = pd.read_parquet(self.splits_dir / "labels.parquet").set_index("post_id")
        
        idx_df = pd.read_parquet(self.ml_dir / "index.parquet")
        self.index = idx_df[idx_df["post_id"].isin(self.split_posts)].reset_index(drop=True)
        
        # Memory-safe shard caching
        self.shard_cache = {}
        self.current_shard_id = None

    def len(self) -> int:
        return len(self.index)

    def get(self, idx: int) -> HeteroData:
        row = self.index.iloc[idx]
        post_id = row["post_id"]
        shard_id = row["shard"]
        
        # Load shard on demand to save RAM
        if shard_id != self.current_shard_id:
            shard_file = self.ml_dir / f"shard_{shard_id}.pt"
            if shard_file.exists():
                self.shard_cache = torch.load(shard_file, weights_only=False)
            else:
                self.shard_cache = {}
            self.current_shard_id = shard_id
            
        rec = self.shard_cache.get(post_id, None)
        y_val = self.labels.loc[post_id, "label"]
        
        data = HeteroData()
        data.y = torch.tensor([to_target(y_val)], dtype=torch.float32)
        
        if rec is not None:
            data["user"].x = torch.tensor(rec["user_x"], dtype=torch.float32)
            data["post"].x = torch.tensor(rec["post_x"], dtype=torch.float32)
            
            # Forward Edges
            data["user", "follows", "user"].edge_index = torch.tensor(rec["follows"], dtype=torch.long)
            data["user", "interacts", "post"].edge_index = torch.tensor(rec["interacts"], dtype=torch.long)
            
            if "interacts_attr" in rec and len(rec["interacts_attr"]) > 0:
                data["user", "interacts", "post"].edge_attr = torch.tensor(rec["interacts_attr"], dtype=torch.float32)
                
            # Reverse Edges (Critical for HGT message passing from Post -> User)
            data["post", "rev_interacts", "user"].edge_index = torch.tensor(
                np.flip(rec["interacts"], axis=0).copy(), dtype=torch.long
            )
            data["user", "followed_by", "user"].edge_index = torch.tensor(
                np.flip(rec["follows"], axis=0).copy(), dtype=torch.long
            )
        else:
            # Fallback for testing if shard cache is missing
            data["post"].x = torch.zeros((1, 8), dtype=torch.float32)
            data["post", "rev_interacts", "user"].edge_index = torch.empty((2, 0), dtype=torch.long)
            data["user", "followed_by", "user"].edge_index = torch.empty((2, 0), dtype=torch.long)
            
        return data


def get_dataloaders(cfg: Config, config_hash: str, batch_size: int = 32, num_workers: int = 0):
    """
    Returns PyTorch Geometric DataLoaders which handle HeteroData graph batching automatically.
    """
    log.info(f"Loading sharded datasets for {cfg.dataset_name} (Hash: {config_hash})...")
    
    train_dataset = PostGraphDataset(cfg, split="train", config_hash=config_hash)
    val_dataset = PostGraphDataset(cfg, split="val", config_hash=config_hash)
    test_dataset = PostGraphDataset(cfg, split="test", config_hash=config_hash)
    
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=num_workers)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers)
    
    log.info(f"Batches (size {batch_size}) -> Train: {len(train_loader)}, Val: {len(val_loader)}, Test: {len(test_loader)}")
    
    return train_loader, val_loader, test_loader